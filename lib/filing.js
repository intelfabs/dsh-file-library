/**
 * "File this": materialize one indexed attachment inside a session workspace.
 *
 * The destination is always `<workspace>/library/`. A file's identity is its
 * SHA-256, so filing the same object twice is a no-op. The manifest is the
 * source of truth and `INDEX.md` is regenerated from it after every change.
 */
import { copyFile, lstat, mkdir, readFile, realpath, rename, rm, stat, access } from 'node:fs/promises'
import { join, isAbsolute } from 'node:path'
import {
  atomicWrite, baseDisplayName, escapeMarkdownCell, hashFile, isInside, isSafeSegment,
  sanitizeSegment, withCollisionSuffix, withExtension,
} from './util.js'

export const MANIFEST_NAME = '.manifest.json'
export const INDEX_NAME = 'INDEX.md'
const RESERVED = new Set([MANIFEST_NAME.toLowerCase(), INDEX_NAME.toLowerCase()])

/** Normalize tags supplied by a client or a tool. */
export function normalizeTags(tags) {
  if (!Array.isArray(tags)) return []
  const out = []
  for (const tag of tags) {
    if (typeof tag !== 'string') continue
    const text = tag.trim().replace(/\s+/g, ' ').slice(0, 32)
    if (text === '' || out.includes(text)) continue
    out.push(text)
    if (out.length >= 8) break
  }
  return out
}

/** Validate and shape one manifest row. */
function normalizeManifestFile(file) {
  if (file === null || typeof file !== 'object') return undefined
  if (typeof file.sha !== 'string' || !/^[a-f0-9]{64}$/.test(file.sha)) return undefined
  if (typeof file.name !== 'string' || !isSafeSegment(file.name)) return undefined
  return {
    sha: file.sha,
    name: file.name,
    mime: typeof file.mime === 'string' ? file.mime : 'application/octet-stream',
    bytes: Number.isFinite(file.bytes) ? Math.max(0, Math.trunc(file.bytes)) : 0,
    addedAt: typeof file.addedAt === 'string' ? file.addedAt : new Date(0).toISOString(),
    tags: normalizeTags(file.tags),
    source: {
      sessionId: typeof file.source?.sessionId === 'string' ? file.source.sessionId : '',
      title: typeof file.source?.title === 'string' ? file.source.title : '',
    },
  }
}

/** Read `<workspace>/library/.manifest.json`; a corrupt manifest is an error. */
export async function readManifest(workspace) {
  const manifestPath = join(workspace, 'library', MANIFEST_NAME)
  let raw
  try {
    raw = await readFile(manifestPath, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return { version: 1, files: [] }
    throw error
  }
  let parsed
  try {
    parsed = JSON.parse(raw)
  } catch {
    throw new Error('library manifest is not valid JSON; refusing to overwrite it')
  }
  if (parsed === null || typeof parsed !== 'object' || !Array.isArray(parsed.files)) {
    throw new Error('library manifest has an unexpected shape; refusing to overwrite it')
  }
  return { version: 1, files: parsed.files.map(normalizeManifestFile).filter(Boolean) }
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
}

/** Render `library/INDEX.md` from the manifest. */
export function renderIndex(manifest) {
  const lines = [
    '# File library',
    '',
    'Files filed from DSH chats into this workspace. Every link is relative to this file.',
    '',
  ]
  if (manifest.files.length === 0) {
    lines.push('_Nothing filed yet._')
  } else {
    lines.push('| File | Type | Size | Added | Source session | Tags | SHA-256 |')
    lines.push('| --- | --- | --- | --- | --- | --- | --- |')
    const sorted = [...manifest.files].sort((a, b) => (b.addedAt < a.addedAt ? -1 : b.addedAt > a.addedAt ? 1 : a.name.localeCompare(b.name)))
    for (const file of sorted) {
      const source = file.source.title === '' ? file.source.sessionId : `${file.source.title} (${file.source.sessionId.slice(0, 8)})`
      const tags = file.tags.length === 0 ? '' : file.tags.join(', ')
      lines.push(`| [${escapeMarkdownCell(file.name)}](./${encodeURI(file.name)}) | ${escapeMarkdownCell(file.mime)} | ${formatBytes(file.bytes)} | ${file.addedAt} | ${escapeMarkdownCell(source)} | ${escapeMarkdownCell(tags)} | \`${file.sha.slice(0, 12)}\` |`)
    }
  }
  lines.push('', `_${manifest.files.length} file${manifest.files.length === 1 ? '' : 's'} · generated by dsh-file-library 0.2.1_`, '')
  return lines.join('\n')
}

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/**
 * Create a filer bound to one host home. Calls are serialized so two clicks
 * cannot interleave a manifest read-modify-write.
 */
export function createFiler(options) {
  const home = options.home
  const limits = options.limits
  const now = options.now ?? (() => new Date())
  const queue = []
  let tail = Promise.resolve()

  const serialized = (work) => {
    const run = tail.then(work, work)
    tail = run.then(() => undefined, () => undefined)
    queue.push(run)
    return run
  }

  const fileThis = (request) => serialized(async () => {
    const entry = request.entry
    const tags = normalizeTags(request.tags)
    if (entry === null || typeof entry !== 'object' || !/^[a-f0-9]{64}$/.test(entry.sha256 ?? '')) {
      throw new Error('entry is not an indexed attachment')
    }
    if (request.signal?.aborted === true) throw new Error('filing was cancelled')
    const workspace = request.workspace
    if (typeof workspace !== 'string' || workspace === '') throw new Error('session workspace is unknown')
    if (!isAbsolute(workspace)) throw new Error('session workspace is not an absolute path')
    const workspaceStat = await stat(workspace).catch(() => undefined)
    if (workspaceStat === undefined || !workspaceStat.isDirectory()) throw new Error('session workspace is not a directory')

    const objectPath = entry.objectPath
    if (typeof objectPath !== 'string' || !isInside(join(home, 'attachments', 'v1', 'objects'), objectPath)) {
      throw new Error('attachment object path is outside the attachment store')
    }
    const objectStat = await stat(objectPath).catch(() => undefined)
    if (objectStat === undefined || !objectStat.isFile()) throw new Error('attachment bytes are missing')
    if (objectStat.size > limits.maxCopyBytes) throw new Error('attachment exceeds the copy size cap')

    const libraryDir = join(workspace, 'library')
    // A hostile workspace could have replaced `library` with a link; never
    // publish through it.
    const existingLibrary = await lstat(libraryDir).catch(() => undefined)
    if (existingLibrary?.isSymbolicLink() === true) throw new Error('library directory is a link; refusing to write through it')
    await mkdir(libraryDir, { recursive: true })
    const [realWorkspace, realLibrary] = await Promise.all([realpath(workspace), realpath(libraryDir)])
    if (!isInside(realWorkspace, realLibrary)) throw new Error('library directory escapes the workspace')

    const manifest = await readManifest(workspace)
    const deduped = manifest.files.find(file => file.sha === entry.sha256)
    if (deduped !== undefined) {
      const target = join(libraryDir, deduped.name)
      const present = await exists(target)
      if (!present) {
        await copyObject(objectPath, target, limits)
      }
      return resultFor(deduped, target, true)
    }

    const originalName = typeof entry.name === 'string' ? entry.name : `attachment.${entry.ext ?? 'bin'}`
    // A hostile name is rejected, not repaired: separators, NUL, a drive
    // letter/UNC prefix, or a dot segment never reach the destination join.
    if (/[\\/\u0000]/.test(originalName) || /^[A-Za-z]:/.test(originalName) || /(^|[\\/])\.\.([\\/]|$)/.test(originalName)) {
      throw new Error('attachment name contains a path separator')
    }
    const displayName = baseDisplayName(originalName)
    if (RESERVED.has(displayName.toLowerCase())) throw new Error('attachment name is reserved')
    if (!isSafeSegment(sanitizeSegment(displayName))) throw new Error('attachment name is not a safe file name')

    const wanted = withExtension(sanitizeSegment(displayName), entry.ext ?? 'bin')
    const taken = new Set(manifest.files.map(file => file.name.toLowerCase()))
    let name = wanted
    for (let suffix = 2; taken.has(name.toLowerCase()) || await exists(join(libraryDir, name)) || RESERVED.has(name.toLowerCase()); suffix += 1) {
      name = withCollisionSuffix(wanted, suffix)
      if (suffix > 999) throw new Error('too many files with the same name')
    }

    const target = join(libraryDir, name)
    if (!isInside(libraryDir, target) || !isSafeSegment(name)) throw new Error('destination escapes the library')
    await copyObject(objectPath, target, limits)

    const file = {
      sha: entry.sha256,
      name,
      mime: typeof entry.mediaType === 'string' ? entry.mediaType : 'application/octet-stream',
      bytes: objectStat.size,
      addedAt: now().toISOString(),
      tags,
      source: {
        sessionId: typeof request.source?.sessionId === 'string' && request.source.sessionId !== ''
          ? request.source.sessionId
          : (typeof entry.sessionId === 'string' ? entry.sessionId : ''),
        title: typeof request.source?.title === 'string' && request.source.title !== ''
          ? request.source.title
          : (typeof entry.sessionTitle === 'string' ? entry.sessionTitle : ''),
      },
    }
    manifest.files.push(file)
    await writeLibrary(workspace, manifest)
    return resultFor(file, target, false)
  })

  async function copyObject(objectPath, target, limits) {
    const temp = join(join(target, '..'), `.${Date.now()}-${Math.random().toString(16).slice(2)}.part`)
    try {
      await copyFile(objectPath, temp)
      const check = await hashFile(temp, { maxBytes: limits.maxHashBytes })
      if (!check.truncated) {
        // The object's name is its digest; verify the bytes we materialized.
        const sourceDigest = targetDigestFromPath(objectPath)
        if (sourceDigest !== undefined && check.sha !== sourceDigest) {
          throw new Error('copied attachment failed digest verification')
        }
      }
      await rename(temp, target)
    } finally {
      await rm(temp, { force: true })
    }
  }

  async function writeLibrary(workspace, manifest) {
    const libraryDir = join(workspace, 'library')
    const ordered = { version: 1, updatedAt: now().toISOString(), files: manifest.files }
    await atomicWrite(join(libraryDir, MANIFEST_NAME), `${JSON.stringify(ordered, null, 2)}\n`)
    await atomicWrite(join(libraryDir, INDEX_NAME), renderIndex(ordered))
  }

  return {
    fileThis,
    readManifest: workspace => readManifest(workspace),
    pending: () => Promise.all(queue),
  }
}

function targetDigestFromPath(objectPath) {
  const name = objectPath.split(/[\\/]/).at(-1) ?? ''
  return /^[a-f0-9]{64}$/.test(name) ? name : undefined
}

function resultFor(file, target, deduped) {
  return {
    sha: file.sha,
    name: file.name,
    displayName: baseDisplayName(file.name),
    bytes: file.bytes,
    mime: file.mime,
    addedAt: file.addedAt,
    tags: file.tags,
    path: target,
    relativePath: `library/${file.name}`,
    reference: `@library/${file.name}`,
    deduped,
  }
}
